// Callback from HAL
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim) {
    if (htim->Instance == TIM3 && overflowCtrl.overflowActive) {
        HAL_GPIO_TogglePin(LD1_GPIO_Port, LD1_Pin);
    }
}

void HAL_GPIO_EXTI_Callback(uint16_t GPIO_Pin) {
    if (GPIO_Pin == USER_Btn_Pin) {
        txCtrl.buttonPressed = HAL_GPIO_ReadPin(USER_Btn_GPIO_Port, USER_Btn_Pin);
        txCtrl.currentProtocol = txCtrl.buttonPressed ? PROTOCOL_SPI : PROTOCOL_I2C;
    }
}

void HAL_ADC_LevelOutOfWindowCallback(ADC_HandleTypeDef* hadc) {
    if (hadc->Instance == ADC1) {
        // 1. Log fault (required for IEC 62304)
        dacCtrl.overvoltageFault = true;

        // 2. Emergency stop DAC
        HAL_DAC_SetValue(&hdac, DAC_CHANNEL_1, DAC_ALIGN_12B_R, 0);

        // 3. Optional: Trigger recovery
        HAL_Delay(100);
        HAL_ADC_Start_DMA(hadc, (uint32_t*)adcBuffer, ADC_BUFFER_SIZE);
    }
}

void HAL_SPI_TxCpltCallback(SPI_HandleTypeDef *hspi) {
    if(hspi->Instance == SPI1) {
        HAL_GPIO_WritePin(SPI_CS_GPIO_Port, SPI_CS_Pin, GPIO_PIN_SET);
        txCtrl.transmissionDone = true;
    }
}

void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef* hadc) {
	if(hadc->Instance == ADC1) {
		// Process ADC data
		adcData.rawValue = adcBuffer[0]; // Take first sample
		adcData.voltage = (adcData.rawValue * 3.3f) / 4095.0f; // Convert to voltage (assuming 3.3V reference)
	}
}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart) {
	if (huart->Instance == USART1) {
		usart1Data.errorFlag = true;
		// Log error (required for medical devices)
		Error_Handler(); // Or reset DMA safely
	}
	if (huart->Instance == USART2) {
		HAL_UART_DeInit(&huart2);
		HAL_UART_Init(&huart2);  // Reinitialize
	}
}

// DMA Complete
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart) {
	if (huart->Instance == USART2) {
		memcpy(&usart2Ctrl.receivedFloat, usart2Ctrl.rxBuffer, sizeof(float));
		usart2Ctrl.dataReady = true;

		// Restart DMA reception
		HAL_UART_Receive_DMA(&huart2, usart2Ctrl.rxBuffer, USART2_BUFFER_SIZE);
	}

}

